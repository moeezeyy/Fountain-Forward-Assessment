"""Generates migrations/0002_seed.sql with predictable synthetic test data:
two dealerships, six users (2 admins + 1 viewer each), three vehicles each.

Run from backend/: python scripts/generate_seed.py
Re-run any time to regenerate the seed file deterministically (same ids,
emails, and vehicle data every time; only the password salt changes since
os.urandom is used -- the plaintext password documented in the README
stays the same: "Passw0rd!").
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from app.security import hash_password

SEED_PASSWORD = "Passw0rd!"

DEALERSHIPS = [
    ("dealership-north", "Northgate Motors"),
    ("dealership-lake", "Lakeside Auto"),
]

USERS = [
    # (id, dealership_id, email, role)
    ("user-north-admin1", "dealership-north", "admin1@northgate.test", "admin"),
    ("user-north-admin2", "dealership-north", "admin2@northgate.test", "admin"),
    ("user-north-viewer1", "dealership-north", "viewer1@northgate.test", "viewer"),
    ("user-lake-admin1", "dealership-lake", "admin1@lakeside.test", "admin"),
    ("user-lake-admin2", "dealership-lake", "admin2@lakeside.test", "admin"),
    ("user-lake-viewer1", "dealership-lake", "viewer1@lakeside.test", "viewer"),
]

VEHICLES = [
    # (id, dealership_id, make, model, year, status)
    ("veh-north-1", "dealership-north", "Toyota", "Camry", 2022, "available"),
    ("veh-north-2", "dealership-north", "Honda", "Civic", 2021, "available"),
    ("veh-north-3", "dealership-north", "Ford", "F-150", 2023, "pending"),
    ("veh-lake-1", "dealership-lake", "Subaru", "Outback", 2022, "available"),
    ("veh-lake-2", "dealership-lake", "Mazda", "CX-5", 2020, "sold"),
    ("veh-lake-3", "dealership-lake", "Chevrolet", "Equinox", 2023, "available"),
]


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main():
    lines = [
        "-- Generated by scripts/generate_seed.py. Re-run to regenerate.",
        "DELETE FROM vehicles;",
        "DELETE FROM users;",
        "DELETE FROM dealerships;",
        "",
    ]

    for did, name in DEALERSHIPS:
        lines.append(
            f"INSERT INTO dealerships (id, name) VALUES ({sql_str(did)}, {sql_str(name)});"
        )

    lines.append("")
    for uid, did, email, role in USERS:
        pw_hash = hash_password(SEED_PASSWORD)
        lines.append(
            "INSERT INTO users (id, dealership_id, email, password_hash, role, token_version) "
            f"VALUES ({sql_str(uid)}, {sql_str(did)}, {sql_str(email)}, {sql_str(pw_hash)}, "
            f"{sql_str(role)}, 1);"
        )

    lines.append("")
    for vid, did, make, model, year, status in VEHICLES:
        lines.append(
            "INSERT INTO vehicles (id, dealership_id, make, model, year, status, version) "
            f"VALUES ({sql_str(vid)}, {sql_str(did)}, {sql_str(make)}, {sql_str(model)}, "
            f"{year}, {sql_str(status)}, 1);"
        )

    out_path = Path(__file__).resolve().parent.parent / "migrations" / "0002_seed.sql"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out_path}")
    print(f"All seeded users share the password: {SEED_PASSWORD}")


if __name__ == "__main__":
    main()
